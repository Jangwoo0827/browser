// Chromium caches an unpacked extension's service worker and only notices a change when the *main* script differs.
// Edits inside ES-module imports (modules/*/background.js) were silently ignored after a restart. So the service worker
// entry (sw.js, generated, untracked) carries a hash of every extension file: any change -> new main script -> reinstall.
// Usage: node scripts/stamp-build.mjs   (run by launch.ps1 and check-extension.mjs)
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ext = join(dirname(dirname(fileURLToPath(import.meta.url))), "extensions", "fjord");

function walk(dir) {
  return readdirSync(dir).sort().flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const hash = createHash("sha1");
for (const f of walk(ext)) {
  if (f.endsWith("sw.js")) continue;
  hash.update(f.slice(ext.length));
  hash.update(readFileSync(f));
}
const body = `// build ${hash.digest("hex").slice(0, 16)} (generated by scripts/stamp-build.mjs; do not edit)\nimport "./background.js";\n`;
const target = join(ext, "sw.js");
if (!existsSync(target) || readFileSync(target, "utf8") !== body) writeFileSync(target, body);
console.log("sw.js", body.split("\n")[0]);
